import { build } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const standaloneRoot = resolve(__dirname, '..');
const engineSrcDir = resolve(standaloneRoot, '../engine/src');
const generatedDir = resolve(engineSrcDir, 'generated');

mkdirSync(generatedDir, { recursive: true });

const result = await build({
  entryPoints: [resolve(standaloneRoot, 'src/main.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: ['es2020'],
  minify: true,
  alias: {
    '@quest-forge/engine/schema': resolve(engineSrcDir, 'schema.ts'),
    '@quest-forge/engine/runtime': resolve(engineSrcDir, 'runtime.ts'),
    '@quest-forge/engine/i18n': resolve(engineSrcDir, 'i18n.ts'),
    '@quest-forge/engine/markdown': resolve(engineSrcDir, 'markdown.ts'),
  },
});

const output = result.outputFiles[0];
if (!output) {
  throw new Error('Standalone build produced no output');
}

const cssContent = readFileSync(resolve(engineSrcDir, 'themes.css'), 'utf8');
const generatedTs = `// Auto-generated by @quest-forge/standalone build script. Do not edit manually.
export const STANDALONE_SCRIPT = ${JSON.stringify(output.text)};
export const STANDALONE_CSS = ${JSON.stringify(cssContent)};
`;

writeFileSync(resolve(generatedDir, 'standalone-assets.ts'), generatedTs, 'utf8');
console.log(
  `Built standalone bundle (${Buffer.byteLength(output.text, 'utf8')} bytes JS, ${Buffer.byteLength(cssContent, 'utf8')} bytes CSS)`,
);
