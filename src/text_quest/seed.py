def seed_demo(db: Session) -> Quest:
    quest = Quest(title=DEMO_TITLE, description=DEMO_DESCRIPTION)
    db.add(quest)
    db.flush()

    ids: dict[str, int] = {}
    for key, title, text, ending, px, py in SCENES:
        scene = Scene(
            quest_id=quest.id,
            title=title,
            text=text,
            ending=ending,
            pos_x=px,
            pos_y=py,
        )
        db.add(scene)
        db.flush()
        ids[key] = scene.id

    for scene_key, text, target_key, required, given in CHOICES:
        db.add(Choice(
            scene_id=ids[scene_key],
            text=text,
            target_scene_id=ids[target_key] if target_key else None,
            required_item=required,
            item_given=given,
        ))

    quest.start_scene_id = ids["gate"]
    db.add(quest)
    db.commit()
    db.refresh(quest)
    return quest


