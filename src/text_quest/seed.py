def seed_indie_dev(db: Session) -> Quest:
    quest = Quest(
        title=INDIE_TITLE,
        description=INDIE_DESCRIPTION,
        initial_variables=INDIE_INITIAL_VARS,
    )
    db.add(quest)
    db.flush()

    ids: dict[str, int] = {}
    for key, title, text, ending, px, py in INDIE_SCENES:
        scene = Scene(
            quest_id=quest.id,
            title=title,
            text=text,
            ending=ending,
            pos_x=px,
            pos_y=py,
        )
        db.add(scene)
        db.flush()
        ids[key] = scene.id

    for scene_key, text, target_key, req_item, give_item, conds, acts in INDIE_CHOICES:
        db.add(Choice(
            scene_id=ids[scene_key],
            text=text,
            target_scene_id=ids[target_key] if target_key else None,
            required_item=req_item,
            item_given=give_item,
            conditions=conds,
            actions=acts,
        ))

    quest.start_scene_id = ids["quit_office"]
    db.add(quest)
    db.commit()
    db.refresh(quest)
    return quest


def seed_if_empty(db: Session) -> None:
    """Наполняем БД демо-квестами, если их ещё нет."""
    if db.exec(select(Quest).where(Quest.title == DEMO_TITLE)).first() is None:
        seed_demo(db)
    if db.exec(select(Quest).where(Quest.title == INDIE_TITLE)).first() is None:
        seed_indie_dev(db)
